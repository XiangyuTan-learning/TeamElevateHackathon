export const LANGUAGES = [
  { code: 'en', label: 'English', locale: 'en-AU', dir: 'ltr' },
  { code: 'zh', label: '简体中文', locale: 'zh-CN', dir: 'ltr' },
  { code: 'vi', label: 'Tiếng Việt', locale: 'vi-VN', dir: 'ltr' },
  { code: 'ar', label: 'العربية', locale: 'ar', dir: 'rtl' },
] as const;
export type LangCode = (typeof LANGUAGES)[number]['code'];
const DICTS: Record<LangCode, Dict> = { en, zh, vi, ar };

function initialLang(): LangCode {
  const saved = localStorage.getItem('lang');
  if (LANGUAGES.some((l) => l.code === saved)) return saved as LangCode;
  const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return (LANGUAGES.find((l) => l.code === nav)?.code ?? 'en') as LangCode;
}

interface I18n {
  lang: LangCode;
  setLang: (l: LangCode) => void;
  t: (key: Key, params?: Record<string, string | number>) => string;
  locale: string;
  dir: 'ltr' | 'rtl';
  /** Translates API errors that carry a code. Other errors show their original message. */
  errorText: (e: unknown) => string;
}
const Ctx = createContext<I18n>(null as never);
export const useI18n = () => useContext(Ctx);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>(initialLang);
  const value = useMemo<I18n>(() => {
    const meta = LANGUAGES.find((l) => l.code === lang)!;
    const t: I18n['t'] = (key, params) => {
      const s = DICTS[lang][key] ?? en[key] ?? key;
      return s.replace(/\{(\w+)\}/g, (_, k) => String(params?.[k] ?? ''));
    };
    const errorText = (e: unknown) => {
      if (e instanceof ApiError && e.code) {
        const key = `err_${e.code}` as Key;
        if (key in en) return t(key, { label: e.params?.slot ? t(`slot_${e.params.slot}` as Key) : '' });
      }
      return e instanceof Error ? e.message : t('err_generic');
    };
    return { lang, setLang: (l) => { localStorage.setItem('lang', l); setLangState(l); }, t, locale: meta.locale, dir: meta.dir, errorText };
  }, [lang]);
  useEffect(() => { document.title = value.t('appTitle'); }, [value]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function LangSwitch() {
  const { lang, setLang, t } = useI18n();
  return (
    <label className="langswitch">
      <span className="sr">{t('language')}</span>
      <select value={lang} onChange={(e) => setLang(e.target.value as LangCode)} aria-label={t('language')}>
        {LANGUAGES.map((l) => <option key={l.code} value={l.code}>{l.label}</option>)}
      </select>
    </label>
  );
}

/** Wraps family-facing pages so text direction follows the chosen language without affecting the staff portals. */
export function LangRoot({ children }: { children: ReactNode }) {
  const { lang, dir } = useI18n();
  return <div dir={dir} lang={lang}>{children}</div>;
}
